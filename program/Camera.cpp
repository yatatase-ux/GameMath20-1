#include "Main.h"
#include "Game.h"
#include "Camera.h"
#include "Random.h"

//---------------------------------------------------------------------------------
//	初期化処理
//---------------------------------------------------------------------------------
void Camera::Init()
{
	//	カメラ座標
	m_pos.Set( 0.0f, 10.0f, -15.0f );
	//	カメラの向き
	m_rot.Set( 30.0f, 0.0f, 0.0f );
}
//---------------------------------------------------------------------------------
//	更新処理
//---------------------------------------------------------------------------------
void Camera::Update()
{
}
//---------------------------------------------------------------------------------
//	描画前のカメラ設定
//---------------------------------------------------------------------------------
void Camera::Setting()
{
	//	カメラ座標と向きを渡してカメラ設定
	SetCameraPositionAndAngle( m_pos.VGet(), TO_RADIAN( m_rot.x ), TO_RADIAN( m_rot.y ), TO_RADIAN( m_rot.z ) );
}
//---------------------------------------------------------------------------------
//	終了処理
//---------------------------------------------------------------------------------
void Camera::Exit()
{
}
